# -*- coding: utf-8 -*-
"""自动生成 LoreKeeper 的 chunk 级 gold（页面级 gold 的补充，用于公平评估 rerank）。

规则：对每题 gold_pages 里的每个页面，取该页内与问题向量余弦相似度最高的 chunk 作为 gold_chunk。
标注：**自动生成（auto-generated），非人工**——报告中必须标注，不得当人工 gold。

输出：data/eval/lorekeeper_chunk_gold.json
"""
from __future__ import annotations

import importlib.util
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

import jieba  # noqa: E402
import lancedb  # noqa: E402
from rank_bm25 import BM25Plus  # noqa: E402

from anchorline.config import Settings  # noqa: E402
from anchorline.llm import EmbeddingClient, ReaderConfig  # noqa: E402

LK = r"C:\Users\Liu\Desktop\ai实验\MiniMax\AI项目\lorekeeper"
LK_CASES = os.path.join(LK, "backend", "app", "eval", "cases.py")
LK_LANCE = os.path.join(LK, "data", "lance")
LK_EMBED = "BAAI/bge-m3"
OUT = os.path.join(ROOT, "data", "eval", "lorekeeper_chunk_gold.json")


def load_cases() -> list:
    spec = importlib.util.spec_from_file_location("lk_cases", LK_CASES)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["lk_cases"] = mod
    spec.loader.exec_module(mod)  # type: ignore[union-attr]
    return mod.all_cases()


def cosine(a: list[float], b: list[float]) -> float:
    dot = sum(x * y for x, y in zip(a, b))
    na = math.sqrt(sum(x * x for x in a))
    nb = math.sqrt(sum(y * y for y in b))
    return dot / (na * nb) if na and nb else 0.0


def main() -> int:
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--by", choices=["vector", "bm25"], default="vector", help="选 gold chunk 的依据（bm25 更中立）")
    args = ap.parse_args()
    out_path = OUT if args.by == "vector" else OUT.replace(".json", "_bm25.json")

    s = Settings()
    emb = EmbeddingClient(ReaderConfig(s.siliconflow_base_url, s.siliconflow_api_key, LK_EMBED))
    db = lancedb.connect(LK_LANCE)
    cases = [c for c in load_cases() if c.gold_pages]
    print(f"cases with gold_pages: {len(cases)} by={args.by}")

    rows = []
    for i, case in enumerate(cases, 1):
        game = case.game
        if game not in ("sr", "ys", "zzz"):
            continue
        tbl = db.open_table(f"kb_{game}_baai-bge-m3_base")
        chunks = tbl.to_arrow().select(["id", "page_title", "text", "vector"]).to_pylist()
        qv = emb.embed([case.question])[0] if args.by == "vector" else None
        gold_pages = set(case.gold_pages)
        by_page: dict[str, list[dict]] = {}
        for c in chunks:
            page = c.get("page_title") or ""
            if page in gold_pages:
                by_page.setdefault(page, []).append(c)
        gold_chunks = []
        for page, items in by_page.items():
            if args.by == "vector":
                best = max(items, key=lambda c: cosine(qv, list(c.get("vector") or [])))
                score = cosine(qv, list(best.get("vector") or []))
            else:
                tokens = [t for t in jieba.lcut(case.question) if t.strip()]
                bm = BM25Plus([[t for t in jieba.lcut(c.get("text") or "") if t.strip()] for c in items])
                scores = bm.get_scores(tokens)
                idx = max(range(len(items)), key=lambda j: float(scores[j]))
                best = items[idx]
                score = float(scores[idx])
            gold_chunks.append({"page": page, "chunk_id": best["id"], "score": round(score, 4)})
        rows.append({"case_id": case.case_id, "game": game, "question": case.question, "gold_chunks": gold_chunks})
        print(f"  [{i}/{len(cases)}] {case.case_id} gold_pages={len(gold_pages)} gold_chunks={len(gold_chunks)}")

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(
            {"note": f"auto-generated by {args.by}: per gold page, best-matching chunk", "rows": rows},
            f,
            ensure_ascii=False,
            indent=1,
        )
    print("written:", out_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
